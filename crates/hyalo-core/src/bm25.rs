//! BM25 ranked search with multi-language stemming support.
//!
//! This module provides:
//! - [`StemLanguage`]: enum of supported stemming languages with [`parse_language`]
//! - [`resolve_language`]: language precedence logic (frontmatter > CLI > config > English)
//! - [`tokenize`]: Unicode-aware tokenization + stemming pipeline
//!
//! Ranked snippet qualification (iteration 283): a body line qualifies when it
//! contains a positive query leaf: any stem alternative of a plain term, a token
//! starting with a `prefix*`, or the complete consecutive stemmed sequence for a
//! quoted phrase. OR accepts any positive side; excluded terms and field terms
//! never supply snippets. Query tokens carry one stem per corpus language
//! (iteration 302); body tokens use the document language, exactly as scoring does.
//! CJK uses the same overlapping bigrams, including single-character unigrams.
//! Frontmatter never qualifies, but raw body code/fence/comment lines do. Phrases
//! spanning lines and title-only hits may therefore have an empty matches array.
//! Within section scope, prioritize the number of distinct positive query tokens
//! present on each qualifying line, then document order, keeping at most three.
//! Snippets keep original text, one-based full-file lines and heading context.
//! - [`Bm25InvertedIndex`]: serializable in-memory BM25 index built from [`DocumentInput`] values

use std::collections::{HashMap, HashSet};

use rust_stemmers::{Algorithm, Stemmer};
use serde::{Deserialize, Serialize};

// ---------------------------------------------------------------------------
// Language (generated by macro to keep enum, canonical_name, to_algorithm,
// and parse_language in sync with a single source of truth)
// ---------------------------------------------------------------------------

macro_rules! define_stem_languages {
    ( default = $default:ident; $( $variant:ident => $canonical:literal, $algo:ident; )+ ) => {
        /// A stemming language supported by the [`rust_stemmers`] crate.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        pub enum StemLanguage { $( $variant, )+ }

        impl Default for StemLanguage {
            fn default() -> Self { Self::$default }
        }

        impl StemLanguage {
            pub(crate) fn to_algorithm(self) -> Algorithm {
                match self { $( Self::$variant => Algorithm::$algo, )+ }
            }

            /// Returns the lowercase canonical name for this language variant.
            pub fn canonical_name(self) -> &'static str {
                match self { $( Self::$variant => $canonical, )+ }
            }
        }

        /// Parses a language name string (case-insensitive) into a [`StemLanguage`].
        ///
        /// Accepts full names (e.g. "english") or ISO 639-1 codes (e.g. "en").
        /// Returns an error for unrecognised language names.
        pub fn parse_language(s: &str) -> anyhow::Result<StemLanguage> {
            let lower = s.to_lowercase();
            // Try canonical (full) names first.
            match lower.as_str() {
                $( $canonical => return Ok(StemLanguage::$variant), )+
                _ => {}
            }
            // Try ISO 639-1 two-letter codes.
            match iso639_to_canonical(lower.as_str()) {
                Some(lang) => Ok(lang),
                None => anyhow::bail!(
                    "unknown stemming language: {s:?} (use a full name like \"english\" or an ISO 639-1 code like \"en\")"
                ),
            }
        }
    };
}

/// Map ISO 639-1 two-letter codes to [`StemLanguage`] variants.
fn iso639_to_canonical(code: &str) -> Option<StemLanguage> {
    match code {
        "ar" => Some(StemLanguage::Arabic),
        "da" => Some(StemLanguage::Danish),
        "nl" => Some(StemLanguage::Dutch),
        "en" => Some(StemLanguage::English),
        "fi" => Some(StemLanguage::Finnish),
        "fr" => Some(StemLanguage::French),
        "de" => Some(StemLanguage::German),
        "el" => Some(StemLanguage::Greek),
        "hu" => Some(StemLanguage::Hungarian),
        "it" => Some(StemLanguage::Italian),
        "no" | "nb" | "nn" => Some(StemLanguage::Norwegian),
        "pt" => Some(StemLanguage::Portuguese),
        "ro" => Some(StemLanguage::Romanian),
        "ru" => Some(StemLanguage::Russian),
        "es" => Some(StemLanguage::Spanish),
        "sv" => Some(StemLanguage::Swedish),
        "ta" => Some(StemLanguage::Tamil),
        "tr" => Some(StemLanguage::Turkish),
        _ => None,
    }
}

