/// Positive leaves compiled once for ranked body snippets. Shares scoring's
/// compiled query, so operators, negation, phrases, prefixes, per-language
/// stem alternatives and CJK never drift.
pub struct SnippetQuery {
    matcher: query::SnippetMatcher,
}

/// Resolve a ranked-search live read using the vault's canonical boundary.
/// Return the checked destination so callers do not reopen the original symlink.
/// This is a pre-open check, not a guarantee against concurrent filesystem changes.
pub fn resolve_document_path(
    dir: &std::path::Path,
    rel_path: &str,
) -> anyhow::Result<std::path::PathBuf> {
    use anyhow::Context;
    let canonical_dir = crate::discovery::canonicalize_vault_dir(dir)?;
    let path = dunce::canonicalize(dir.join(rel_path))
        .with_context(|| format!("resolving ranked document {rel_path}"))?;
    if !path.starts_with(&canonical_dir) {
        return Err(crate::discovery::FileResolveError::OutsideVault {
            path: rel_path.to_owned(),
            resolved: Some(path.display().to_string()),
        }
        .into());
    }
    Ok(path)
}

impl SnippetQuery {
    /// Compile with the query-time stemming language (no document override).
    pub fn new(query: &str, language: StemLanguage) -> Self {
        Self::from_compiled(&CompiledQuery::new(query, language))
    }

    /// Build a snippet selector from the same compiled query used for scoring.
    pub fn from_compiled(query: &CompiledQuery) -> Self {
        Self {
            matcher: query::SnippetMatcher::from_compiled(query),
        }
    }

    /// Number of distinct positive query tokens on a qualifying line (zero
    /// when it does not qualify) and the extra positions of its smallest
    /// window over the required groups (DEC-338). Body stemming must use the
    /// same document language as the BM25 corpus.
    fn rank_line(&self, line: &str, stemmer: &Stemmer) -> (usize, u64) {
        let tokens = tokenize(line, stemmer);
        let coverage = self.matcher.coverage(&tokens);
        if coverage == 0 {
            return (0, u64::MAX);
        }
        (coverage, self.matcher.window(&tokens))
    }

    /// Stream one selected result's raw body and keep the best three lines.
    /// Call only after result filtering, sorting and limiting. Snapshot tokens
    /// have no original text or file-line offsets, so cannot supply snippets.
    pub fn snippets(
        &self,
        dir: &std::path::Path,
        rel_path: &str,
        language: StemLanguage,
        sections: &[crate::types::OutlineSection],
        scope: &[crate::heading::SectionRange],
    ) -> anyhow::Result<Vec<crate::types::ContentMatch>> {
        use crate::scanner::{
            FileVisitor, LineOutcome, MAX_BODY_LINE_BYTES, ScanAction, read_line_capped,
        };
        let mut visitor = SnippetVisitor {
            query: self,
            stemmer: create_stemmer(language),
            sections,
            scope,
            best: Vec::with_capacity(4),
            skip_code: search_settings().skip_code_blocks,
            fence: crate::scanner::FenceTracker::new(),
        };
        let path = resolve_document_path(dir, rel_path)?;
        let file = std::fs::File::open(path)?;
        if file.metadata()?.len() > crate::scanner::MAX_FILE_SIZE {
            return Ok(Vec::new());
        }
        let mut reader = std::io::BufReader::new(file);
        let framed = crate::frontmatter::read_frame_for_body(&mut reader, MAX_BODY_LINE_BYTES)?;
        if framed.bytes().is_empty() {
            return Ok(Vec::new());
        }
        let fm_lines = if framed.frame().frontmatter().is_some() {
            memchr::memchr_iter(b'\n', framed.bytes()).count()
                + usize::from(!framed.bytes().ends_with(b"\n"))
        } else {
            0
        };
        let mut line = fm_lines.max(1);
        if fm_lines == 0
            && framed.first_line_complete()
            && let Ok(first_line) = std::str::from_utf8(framed.bytes())
        {
            visitor.on_raw_body_line(first_line.trim_end_matches(['\r', '\n']), line);
        }
        let mut buf = String::new();
        loop {
            buf.clear();
            let (n, outcome) = read_line_capped(&mut reader, &mut buf, MAX_BODY_LINE_BYTES)?;
            if n == 0 {
                break;
            }
            line += 1;
            if outcome == LineOutcome::Complete
                && visitor.on_raw_body_line(buf.trim_end_matches(['\r', '\n']), line)
                    == ScanAction::Stop
            {
                break;
            }
        }
        Ok(visitor.best.into_iter().map(|(_, _, m)| m).collect())
    }
}

struct SnippetVisitor<'a> {
    query: &'a SnippetQuery,
    stemmer: Stemmer,
    sections: &'a [crate::types::OutlineSection],
    scope: &'a [crate::heading::SectionRange],
    best: Vec<(usize, u64, crate::types::ContentMatch)>,
    skip_code: bool,
    fence: crate::scanner::FenceTracker,
}

impl crate::scanner::FileVisitor for SnippetVisitor<'_> {
    fn on_raw_body_line(&mut self, raw: &str, line: usize) -> crate::scanner::ScanAction {
        use crate::scanner::ScanAction;
        // Fence state sees every line, in scope or not.
        let skipped = self.skip_code && self.fence.process_line(raw);
        if skipped || (!self.scope.is_empty() && !crate::heading::in_scope(self.scope, line)) {
            return ScanAction::Continue;
        }
        let (count, window) = self.query.rank_line(raw, &self.stemmer);
        if count == 0 {
            return ScanAction::Continue;
        }
        if self.best.len() == 3 {
            let worst = &self.best[2];
            if (std::cmp::Reverse(worst.0), worst.1) <= (std::cmp::Reverse(count), window) {
                return ScanAction::Continue;
            }
        }
        let section = self
            .sections
            .iter()
            .rev()
            .find(|s| s.line <= line && s.heading.is_some())
            .and_then(|s| {
                s.heading
                    .as_ref()
                    .map(|heading| format!("{} {heading}", "#".repeat(usize::from(s.level))))
            })
            .unwrap_or_default();
        self.best.push((
            count,
            window,
            crate::types::ContentMatch {
                line,
                section,
                text: raw.to_owned(),
            },
        ));
        self.best
            .sort_by_key(|(count, window, m)| (std::cmp::Reverse(*count), *window, m.line));
        self.best.truncate(3);
        // Nothing later can beat three lines carrying every distinct query
        // token with no gap between the required terms; equal rank loses on
        // document order. Particularly useful for common single-term searches
        // over long indexed documents.
        if self.best.len() == 3
            && self.best[2].0 == self.query.matcher.max_coverage()
            && self.best[2].1 == 0
        {
            ScanAction::Stop
        } else {
            ScanAction::Continue
        }
    }

    fn needs_frontmatter(&self) -> bool {
        false
    }
}

