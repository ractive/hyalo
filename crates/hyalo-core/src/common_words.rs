/// Shortest title this module can classify.
///
/// Mirrors the `links auto --min-length` default: shorter titles are never
/// proposed as candidates, so they are never asked about.
pub const MIN_COMMON_WORD_LEN: usize = 3;

/// `true` when `title` is an ordinary English word or a generic documentation
/// filename, and therefore a likely source of auto-link noise.
///
/// Case-insensitive. Regular plurals resolve to their singular before the
/// lookup, so `"Permissions"` is recognised from the stored `permission`:
///
/// - `-ies` → `-y` (`policies` → `policy`)
/// - `-es`  → `-` and `-s` → `-` (`processes` → `process`, `notes` → `note`)
///
/// Non-ASCII titles always return `false`: the list is an English word list and
/// lowercasing non-ASCII correctly is not worth the allocation for a heuristic
/// whose only job is to phrase an advisory note.
///
/// ```
/// use hyalo_core::is_common_word;
/// assert!(is_common_word("permissions"));
/// assert!(is_common_word("README"));
/// assert!(!is_common_word("Kubernetes"));
/// ```
#[must_use]
pub fn is_common_word(title: &str) -> bool {
    let title = title.trim();
    if title.len() < MIN_COMMON_WORD_LEN || !title.is_ascii() {
        return false;
    }
    let lower = title.to_ascii_lowercase();
    if contains(&lower) {
        return true;
    }
    // Regular plurals: try the singular forms, longest suffix first.
    if let Some(stem) = lower.strip_suffix("ies") {
        let mut singular = String::with_capacity(stem.len() + 1);
        singular.push_str(stem);
        singular.push('y');
        if contains(&singular) {
            return true;
        }
    }
    if let Some(stem) = lower.strip_suffix("es")
        && contains(stem)
    {
        return true;
    }
    if let Some(stem) = lower.strip_suffix('s')
        && contains(stem)
    {
        return true;
    }
    false
}

/// Binary search over the sorted static list.
fn contains(needle: &str) -> bool {
    COMMON_WORDS.binary_search(&needle).is_ok()
}

#[cfg(test)]
mod tests {
    use super::{COMMON_WORDS, MIN_COMMON_WORD_LEN, is_common_word};

    #[test]
    fn word_list_is_sorted_deduplicated_and_lowercase() {
        for pair in COMMON_WORDS.windows(2) {
            assert!(
                pair[0] < pair[1],
                "COMMON_WORDS must be sorted and deduplicated: {:?} !< {:?}",
                pair[0],
                pair[1]
            );
        }
        for word in COMMON_WORDS {
            assert!(
                word.is_ascii() && *word == word.to_ascii_lowercase(),
                "COMMON_WORDS entries must be ASCII lowercase: {word:?}"
            );
            assert!(
                word.len() >= MIN_COMMON_WORD_LEN,
                "COMMON_WORDS entries must be at least {MIN_COMMON_WORD_LEN} chars: {word:?}"
            );
        }
    }

    #[test]
    fn matches_plain_words_case_insensitively() {
        assert!(is_common_word("index"));
        assert!(is_common_word("Index"));
        assert!(is_common_word("INDEX"));
        assert!(is_common_word("  note  "));
    }

    #[test]
    fn matches_generic_doc_filenames() {
        for name in ["readme", "README", "changelog", "todo", "license"] {
            assert!(is_common_word(name), "{name} should be a common title");
        }
    }

    #[test]
    fn matches_regular_plurals() {
        assert!(is_common_word("permissions"));
        assert!(is_common_word("notes"));
        assert!(is_common_word("processes"));
        assert!(is_common_word("policies"));
    }

    #[test]
    fn rejects_domain_specific_titles() {
        for title in [
            "Kubernetes",
            "hyalo",
            "frontmatter",
            "wikilink",
            "Corina",
            "aho-corasick",
        ] {
            assert!(!is_common_word(title), "{title} should not be common");
        }
    }

    #[test]
    fn rejects_short_and_empty_titles() {
        assert!(!is_common_word(""));
        assert!(!is_common_word("of"));
        assert!(!is_common_word("a"));
        assert!(!is_common_word("  "));
    }

    #[test]
    fn rejects_non_ascii_titles() {
        // The list is English-only; a non-ASCII title is never classified.
        assert!(!is_common_word("Übersicht"));
        assert!(!is_common_word("données"));
    }

    #[test]
    fn plural_stripping_does_not_invent_words() {
        // "ss" must not be stripped down to a match that isn't there.
        assert!(!is_common_word("zzz"));
        assert!(!is_common_word("zzzs"));
    }
}
