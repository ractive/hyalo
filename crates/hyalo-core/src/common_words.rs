//! Common-English-word detection for auto-link candidate titles (iter-197).
//!
//! `hyalo links auto` turns every page title into a match candidate. On vaults
//! whose page titles double as ordinary English words — `permissions.md`,
//! `index.md`, `notes.md` — that produces prose-mention noise: linking the word
//! "permissions" in a how-to guide to the permissions page is almost never what
//! the author meant. `[links.auto] exclude_titles` (iter-195a) fixes it once the
//! user has noticed, but a first run has no way to tell them.
//!
//! This module answers one narrow question — *is this title an ordinary English
//! word (or a generic documentation filename)?* — so the CLI can raise an
//! advisory `note:` naming the offenders. It is deliberately a bundled static
//! list rather than a dictionary dependency: predictable, allocation-free, no
//! new crate in the tree, and small enough to read.
//!
//! The list holds high-frequency English words plus generic doc filenames
//! (`readme`, `changelog`, `index`, …) and the four platform/format names that
//! show up as note titles in almost every vault while being prose nouns
//! everywhere else (`github`, `gitlab`, `markdown`, `wiki` — iter-267, UX-9).
//! The list stays deliberately narrow there: product and domain nouns a vault
//! genuinely links to (`Obsidian`, `Dataview`, `Canvas`) and words that are
//! plausible page titles in their own right (`config`, `setup`, `template`)
//! are absent, because the frequency trigger already catches the ones that
//! actually flood a run. Words shorter than 3 characters are
//! omitted because `links auto --min-length` defaults to 3 and never proposes
//! them anyway.
//!
//! Matching is case-insensitive and covers regular plurals, so the title
//! "Permissions" is recognised from the stored `permission`.

